import {prepareHandover} from "../src/lib/adminHandover";
import assert from "node:assert/strict";
import {firstReplyWindow, firstReplyState, contactNumber, contactHref, leadReference} from "../src/lib/adminCrm";
import {orderedGallery} from "../src/lib/profileGalleryOrder";
const calendar={from:"2026-11-01",through:"2026-11-30",holidays:["2026-11-09"]}; // Fictional observed holiday for testing only.
const received="2026-11-06T18:30:00Z";
assert.deepEqual(firstReplyWindow(received,calendar),{reminder:"2026-11-10T09:00:00.000Z",deadline:"2026-11-11T17:00:00.000Z"});
assert.deepEqual(firstReplyWindow("2026-11-07T08:00:00Z",calendar),firstReplyWindow(received,calendar));
assert.equal(firstReplyState(received,new Date("2026-11-10T08:59:59Z"),calendar,[]),"awaiting");
assert.equal(firstReplyState(received,new Date("2026-11-10T09:00:00Z"),calendar,[]),"reminder");
assert.equal(firstReplyState(received,new Date("2026-11-11T17:00:00Z"),calendar,[]),"reminder");
const late=new Date("2026-11-11T17:00:01Z");
assert.equal(firstReplyState(received,late,calendar,[]),"overdue");
assert.equal(firstReplyState(received,late,undefined,[]),"unavailable");
assert.equal(firstReplyState(received,late,calendar,null),"unavailable");
assert.equal(firstReplyWindow("2026-11-30",calendar),null);
const contact={recipient:"buyer" as const,confirmed:true,occurredAt:"2026-11-10T10:00:00Z"};
assert.equal(firstReplyState(received,late,calendar,[{...contact,recipient:"supplier"}]),"overdue");
assert.equal(firstReplyState(received,late,calendar,[{...contact,confirmed:false}]),"overdue");
assert.equal(firstReplyState(received,late,undefined,[contact]),"recorded");
assert.equal(leadReference("8a203c01-f4ae-4000-8000-000000000001"),"BR-8A203C01F4");
assert.equal(contactNumber("024 000 0000"),"+233240000000");
assert.equal(contactNumber("00233 24 000 0000"),"+233240000000");
assert.equal(contactHref("0240000000",false,"wa"),undefined);
for(const invalid of ["","+233000","invalid","0240000000?","javascript:12"])assert.equal(contactHref(invalid,true,"wa"),undefined);
assert.equal(contactHref("0240000000",true,"wa","Hello & hi"),"https://wa.me/233240000000?text=Hello%20%26%20hi");
assert.deepEqual(orderedGallery(["old A","old B"],[{publicUrl:"new B",position:2},{publicUrl:"new A",position:0}]),["new A","old A","new B","old B"]);
assert.deepEqual(orderedGallery(["old"],[{publicUrl:"new"}]),["old","new"]);
assert.deepEqual(prepareHandover({nextAction:"Call Thursday",note:"Check quantity",dueLocal:"2026-11-12T10:00"}),{nextAction:"Call Thursday",note:"Check quantity",dueAt:"2026-11-12T10:00:00.000Z"});
assert.ok("error" in prepareHandover({nextAction:"",note:"",dueLocal:"2026-11-12T10:00"}));
assert.ok("error" in prepareHandover({nextAction:"Call",note:"",dueLocal:"2026-02-31T10:00"}));
console.log("PASS admin CRM deadlines, contact isolation, references and mixed gallery ordering");
